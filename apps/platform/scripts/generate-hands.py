"""Generate src/components/marketing/hands-art.ts from assets/creation-hands.png.

Run: uv run --with pillow --with numpy scripts/generate-hands.py
"""

from collections import deque
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / "assets" / "creation-hands.png"
OUTPUT = ROOT.parent / "src" / "components" / "marketing" / "hands-art.ts"

COLS = 500
CHAR_ASPECT = 0.6
SAT_THRESHOLD = 0.16
MIN_COVERAGE = 0.5
MIN_COMPONENT = 150
SEED = 1505


def hand_mask(hsv: np.ndarray) -> np.ndarray:
    sat = Image.fromarray(hsv[..., 1])
    sat = sat.filter(ImageFilter.GaussianBlur(3))
    mask = Image.fromarray(
        ((np.asarray(sat) / 255) > SAT_THRESHOLD).astype(np.uint8) * 255
    )
    mask = mask.filter(ImageFilter.MinFilter(5)).filter(ImageFilter.MaxFilter(5))
    return np.asarray(mask) > 127


def cell_means(values: np.ndarray, rows: int) -> np.ndarray:
    h, w = values.shape
    ys = np.linspace(0, h, rows + 1).astype(int)
    xs = np.linspace(0, w, COLS + 1).astype(int)
    out = np.zeros((rows, COLS))
    for r in range(rows):
        for c in range(COLS):
            out[r, c] = values[ys[r] : ys[r + 1], xs[c] : xs[c + 1]].mean()
    return out


def components(grid: np.ndarray) -> list[list[tuple[int, int]]]:
    rows, cols = grid.shape
    seen = np.zeros_like(grid, dtype=bool)
    found = []
    for r in range(rows):
        for c in range(cols):
            if not grid[r, c] or seen[r, c]:
                continue
            cells = []
            queue = deque([(r, c)])
            seen[r, c] = True
            while queue:
                y, x = queue.popleft()
                cells.append((y, x))
                for ny, nx in ((y + 1, x), (y - 1, x), (y, x + 1), (y, x - 1)):
                    if (
                        0 <= ny < rows
                        and 0 <= nx < cols
                        and grid[ny, nx]
                        and not seen[ny, nx]
                    ):
                        seen[ny, nx] = True
                        queue.append((ny, nx))
            found.append(cells)
    return found


def main() -> None:
    image = Image.open(SOURCE).convert("RGB")
    width, height = image.size
    rows = round(height / (width / COLS / CHAR_ASPECT))

    hsv = np.asarray(image.convert("HSV"))
    value = np.asarray(image.convert("L")) / 255

    coverage = cell_means(hand_mask(hsv).astype(float), rows)
    shade = cell_means(value, rows)

    parts = [p for p in components(coverage > MIN_COVERAGE) if len(p) >= MIN_COMPONENT]
    parts.sort(key=lambda p: np.mean([x for _, x in p]))
    inside = np.zeros((rows, COLS), dtype=bool)
    for part in parts:
        for y, x in part:
            inside[y, x] = True

    lo, hi = np.percentile(shade[inside], [3, 97])
    darkness = np.clip((hi - shade) / (hi - lo), 0, 1)
    probability = 0.55 + 0.45 * darkness

    padded = np.pad(inside, 1)
    edge = inside & ~(
        padded[:-2, 1:-1] & padded[2:, 1:-1] & padded[1:-1, :-2] & padded[1:-1, 2:]
    )

    rng = np.random.default_rng(SEED)
    place = inside & ((rng.random((rows, COLS)) < probability) | edge)
    digits = rng.integers(0, 10, (rows, COLS))
    grid = np.where(place, digits.astype(str), " ")

    used = np.flatnonzero(place.any(axis=1))
    top, bottom = used[0], used[-1] + 1
    left_end = max(x for _, x in parts[0]) + 1
    right_start = min(x for _, x in parts[-1])

    def tip_row(part: list[tuple[int, int]], col: int) -> float:
        ys = [y for y, x in part if x == col]
        return (np.mean(ys) + 0.5 - top) / (bottom - top)

    left_tip = tip_row(parts[0], left_end - 1)
    right_tip = tip_row(parts[-1], right_start)

    def art(cells: np.ndarray) -> str:
        return "\n".join("".join(row).rstrip() for row in cells[top:bottom])

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(
        "// Generated by scripts/generate-hands.py. Do not edit.\n"
        f"export const HANDS_LEFT_COLS = {left_end}\n"
        f"export const HANDS_RIGHT_COLS = {COLS - right_start}\n"
        f"export const HANDS_LEFT_TIP = {left_tip:.4f}\n"
        f"export const HANDS_RIGHT_TIP = {right_tip:.4f}\n"
        f"export const HANDS_LEFT = `{art(grid[:, :left_end])}`\n"
        f"export const HANDS_RIGHT = `{art(grid[:, right_start:])}`\n"
    )
    print(
        f"{COLS}x{rows} -> rows {bottom - top}, left {left_end}, "
        f"right {COLS - right_start}, tips {left_tip:.3f},{right_tip:.3f}"
    )


if __name__ == "__main__":
    main()
